CREATE TABLE reservation (
 id BIGINT NOT NULL AUTO_INCREMENT,
 equipment_id BIGINT NOT NULL,
 student_id BIGINT NOT NULL,
 start_time DATETIME(3) NOT NULL,
 end_time DATETIME(3) NOT NULL,
 purpose VARCHAR(500) NOT NULL,
 status VARCHAR(20) COLLATE utf8mb4_bin NOT NULL,
 idempotency_key VARCHAR(64) COLLATE utf8mb4_bin NOT NULL,
 request_hash CHAR(64) COLLATE utf8mb4_bin NOT NULL,
 created_at DATETIME(3) NOT NULL,
 updated_at DATETIME(3) NOT NULL,
 PRIMARY KEY(id),
 CONSTRAINT uk_reservation_student_key UNIQUE(student_id,idempotency_key),
 KEY idx_reservation_conflict(equipment_id,status,start_time,end_time),
 KEY idx_reservation_quota(student_id,status,end_time),
 KEY idx_reservation_expiry(status,start_time,id),
 KEY idx_reservation_created(created_at,id),
 CONSTRAINT fk_reservation_equipment FOREIGN KEY(equipment_id) REFERENCES equipment(id) ON DELETE RESTRICT,
 CONSTRAINT fk_reservation_student FOREIGN KEY(student_id) REFERENCES sys_user(id) ON DELETE RESTRICT,
 CONSTRAINT ck_reservation_time CHECK(start_time < end_time),
 CONSTRAINT ck_reservation_purpose CHECK(CHAR_LENGTH(TRIM(purpose)) BETWEEN 1 AND 500),
 CONSTRAINT ck_reservation_status CHECK(status IN ('PENDING','APPROVED','REJECTED','CANCELLED','EXPIRED','COMPLETED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE reservation_log (
 id BIGINT NOT NULL AUTO_INCREMENT,
 reservation_id BIGINT NOT NULL,
 operator_id BIGINT NULL,
 action VARCHAR(20) COLLATE utf8mb4_bin NOT NULL,
 from_status VARCHAR(20) COLLATE utf8mb4_bin NULL,
 to_status VARCHAR(20) COLLATE utf8mb4_bin NOT NULL,
 reason VARCHAR(500) NULL,
 created_at DATETIME(3) NOT NULL,
 PRIMARY KEY(id),
 KEY idx_reservation_log_order(reservation_id,created_at,id),
 CONSTRAINT fk_log_reservation FOREIGN KEY(reservation_id) REFERENCES reservation(id) ON DELETE RESTRICT,
 CONSTRAINT fk_log_operator FOREIGN KEY(operator_id) REFERENCES sys_user(id) ON DELETE RESTRICT,
 CONSTRAINT ck_log_action CHECK(action IN ('CREATE','APPROVE','REJECT','CANCEL','REVOKE','EXPIRE','COMPLETE')),
 CONSTRAINT ck_log_from CHECK(from_status IS NULL OR from_status IN ('PENDING','APPROVED','REJECTED','CANCELLED','EXPIRED','COMPLETED')),
 CONSTRAINT ck_log_to CHECK(to_status IN ('PENDING','APPROVED','REJECTED','CANCELLED','EXPIRED','COMPLETED')),
 CONSTRAINT ck_log_operator CHECK((action='EXPIRE' AND operator_id IS NULL) OR (action<>'EXPIRE' AND operator_id IS NOT NULL)),
 CONSTRAINT ck_log_initial CHECK((action='CREATE' AND from_status IS NULL AND to_status='PENDING') OR (action<>'CREATE' AND from_status IS NOT NULL)),
 CONSTRAINT ck_log_reason CHECK(action NOT IN ('REJECT','REVOKE') OR (reason IS NOT NULL AND CHAR_LENGTH(TRIM(reason))>0))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
